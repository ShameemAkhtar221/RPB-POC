package API.Pojo;

public class BasicInfo {
    private String companyName;
    private String designation;
    private String email;
    private String phone;
    private String gitLink;
    private String linkedLink;
    private String basicInfoSummary;


    public String getCompanyName() {
        return companyName;
    }

    public void setCompanyName(String companyName) {
        this.companyName = companyName;
    }

    public String getDesignation() {
        return designation;
    }

    public void setDesignation(String designation) {
        this.designation = designation;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getGitLink() {
        return gitLink;
    }

    public void setGitLink(String gitLink) {
        this.gitLink = gitLink;
    }

    public String getLinkedLink() {
        return linkedLink;
    }

    public void setLinkedLink(String linkedLink) {
        this.linkedLink = linkedLink;
    }

    public String getBasicInfoSummary() {
        return basicInfoSummary;
    }

    public void setBasicInfoSummary(String basicInfoSummary) {
        this.basicInfoSummary = basicInfoSummary;
    }


}
