package API.Pojo;

public class Academic {
    private String academicDegreeName;
    private String academicInstitute;
    private String academicStartsFrom;
    private String academicEndsTo;

    public String getAcademicDegreeName() {
        return academicDegreeName;
    }

    public void setAcademicDegreeName(String academicDegreeName) {
        this.academicDegreeName = academicDegreeName;
    }

    public String getAcademicInstitute() {
        return academicInstitute;
    }

    public void setAcademicInstitute(String academicInstitute) {
        this.academicInstitute = academicInstitute;
    }

    public String getAcademicStartsFrom() {
        return academicStartsFrom;
    }

    public void setAcademicStartsFrom(String academicStartsFrom) {
        this.academicStartsFrom = academicStartsFrom;
    }

    public String getAcademicEndsTo() {
        return academicEndsTo;
    }

    public void setAcademicEndsTo(String academicEndsTo) {
        this.academicEndsTo = academicEndsTo;
    }
}
